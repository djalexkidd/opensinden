"""White screen border used by the lightgun camera to locate the screen.

Two back-ends:
  * "layershell": QML + org.kde.layershell (from kde-screen-borders), run with
    the system `qml6`. Draws above everything on KDE/wlroots Wayland, including
    fullscreen games. Needs the `layer-shell-qt6-imports` package.
  * "qt": a fullscreen, click-through, always-on-top PySide6 window (fallback,
    also works on X11).
"""

