@dataclass
class BorderSettings:
    color: tuple = (255, 255, 255)
    width_percent: float = 2.0          # % of the screen height, like the official app
    outer_enabled: bool = False
    outer_color: tuple = (0, 0, 0)
    outer_width_percent: float = 3.0
    display: int = 0
    method: str = "auto"                 # auto | layershell | qt
    reserve_space: bool = False

    @classmethod
    def from_config(cls, c: Config):
        return cls(
            color=c.get_rgb("BorderColourRGB", (255, 255, 255)),
            width_percent=c.get_float("BorderWidthPercent", 2.0),
            outer_enabled=c.get_bool("OuterBorderEnabled"),
            outer_color=c.get_rgb("OuterBorderColourRGB", (0, 0, 0)),
            outer_width_percent=c.get_float("OuterBorderWidthPercent", 3.0),
            display=c.get_int("BorderDisplay", 0),
            method=c.get("BorderMethod", "auto") or "auto",
            reserve_space=c.get_bool("BorderReserveSpace"),
        )

    def thickness_px(self, screen_height):
        inner = max(1, int(round(screen_height * self.width_percent / 100.0)))
        outer = int(round(screen_height * self.outer_width_percent / 100.0)) if self.outer_enabled else 0
        return inner, outer


def _hex(rgb):
    return "#%02x%02x%02x" % tuple(rgb)


def qml6_binary():
    for name in ("qml6", "qml-qt6", "/usr/lib64/qt6/bin/qml", "/usr/lib/qt6/bin/qml"):
        path = shutil.which(name) or (name if os.path.isfile(name) else None)
        if path:
            return path
    return None


def layershell_available():
    if not qml6_binary():
        return False
    if os.environ.get("XDG_SESSION_TYPE") != "wayland":
        return False
    extra = [d for var in ("QML_IMPORT_PATH", "QML2_IMPORT_PATH")
             for d in os.environ.get(var, "").split(os.pathsep) if d]
    for base in extra + ["/usr/lib64/qt6/qml", "/usr/lib/qt6/qml", "/usr/lib/x86_64-linux-gnu/qt6/qml"]:
        if os.path.isfile(os.path.join(base, "org", "kde", "layershell", "qmldir")):
            return True
    return False


def resolve_method(settings: BorderSettings):
    if settings.method == "layershell" or (settings.method == "auto" and layershell_available()):
        return "layershell"
    return "qt"


def generate_qml(settings: BorderSettings, screen_height):
    inner, outer = settings.thickness_px(screen_height)
    exclusion = "root.total" if settings.reserve_space else "-1"
    return _QML_TEMPLATE % {
        "color": _hex(settings.color),
        "outer_color": _hex(settings.outer_color),
        "thickness": inner,
        "outer": outer,
        "display": int(settings.display),
        "exclusion": exclusion,
    }


class LayerShellBorder:
    """Runs the generated QML in a `qml6` subprocess."""

    def __init__(self, settings: BorderSettings, screen_height):
        self.settings = settings
        self.screen_height = screen_height
        self.proc = None
        self.qml_path = os.path.join(tempfile.gettempdir(), "opensinden-border-%d.qml" % os.getuid())

    def show(self):
        self.hide()
        with open(self.qml_path, "w") as f:
            f.write(generate_qml(self.settings, self.screen_height))
        env = dict(os.environ)
        env["QT_WAYLAND_SHELL_INTEGRATION"] = "layer-shell"
        # stderr goes to a file: an unread pipe could fill up and block qml6.
        self.log_path = self.qml_path + ".log"
        self._log = open(self.log_path, "w")
        self.proc = subprocess.Popen([qml6_binary(), self.qml_path], env=env,
                                     stdout=subprocess.DEVNULL, stderr=self._log)

    def failed(self):
        """True if the qml process died (e.g. missing module)."""
        return self.proc is not None and self.proc.poll() not in (None, 0)

    def error_output(self):
        if self.proc and self.proc.poll() is not None:
            try:
                with open(self.log_path, errors="replace") as f:
                    return f.read()
            except OSError:
                pass
        return ""

    def hide(self):
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(2)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        self.proc = None

    @property
    def visible(self):
        return self.proc is not None and self.proc.poll() is None


class QtBorder:
    """Fullscreen click-through overlay drawn with PySide6."""

    def __init__(self, settings: BorderSettings):
        from PySide6 import QtCore, QtGui, QtWidgets

        settings_ref = settings

        class Overlay(QtWidgets.QWidget):
            def __init__(self):
                super().__init__(None, QtCore.Qt.WindowType.FramelessWindowHint
                                 | QtCore.Qt.WindowType.WindowStaysOnTopHint
                                 | QtCore.Qt.WindowType.WindowTransparentForInput
                                 | QtCore.Qt.WindowType.WindowDoesNotAcceptFocus
                                 | QtCore.Qt.WindowType.Tool)
                self.setAttribute(QtCore.Qt.WidgetAttribute.WA_TranslucentBackground)
                self.setAttribute(QtCore.Qt.WidgetAttribute.WA_ShowWithoutActivating)
                self.setWindowTitle("OpenSinden border")

            def paintEvent(self, _ev):
                s = settings_ref
                p = QtGui.QPainter(self)
                r = self.rect()
                inner, outer = s.thickness_px(r.height())
                if outer:
                    p.fillRect(r, QtGui.QColor(*s.outer_color))
                    p.setCompositionMode(QtGui.QPainter.CompositionMode.CompositionMode_Source)
                    p.fillRect(r.adjusted(outer, outer, -outer, -outer), QtGui.QColor(*s.color))
                else:
                    p.fillRect(r, QtGui.QColor(*s.color))
                p.setCompositionMode(QtGui.QPainter.CompositionMode.CompositionMode_Source)
                t = inner + outer
                p.fillRect(r.adjusted(t, t, -t, -t), QtCore.Qt.GlobalColor.transparent)

        self.settings = settings
        self.widget = Overlay()
        self._QtWidgets = QtWidgets

    def show(self):
        app = self._QtWidgets.QApplication.instance()
        screens = app.screens()
        screen = screens[self.settings.display] if self.settings.display < len(screens) else screens[0]
        self.widget.setScreen(screen)
        self.widget.setGeometry(screen.geometry())
        self.widget.showFullScreen()
        self.widget.update()

    def hide(self):
        self.widget.hide()

    def failed(self):
        return False

    @property
    def visible(self):
        return self.widget.isVisible()


def create_border(settings: BorderSettings, screen_height):
    if resolve_method(settings) == "layershell":
        return LayerShellBorder(settings, screen_height)
    if settings.method == "auto":
        logging.getLogger(__name__).warning(
            "Bordure : module QML org.kde.layershell absent, repli sur une fenêtre Qt qui sera "
            "masquée par les jeux plein écran et parfois par la barre des tâches. "
            "Installez-le : sudo zypper install layer-shell-qt6-imports")
    return QtBorder(settings)


# -- standalone process (used by `opensinden border`) --------------------

def _running_pid():
    try:
        with open(PID_FILE) as f:
            pid = int(f.read().strip())
        os.kill(pid, 0)
        return pid
    except (OSError, ValueError):
        return None


def stop_standalone():
    pid = _running_pid()
    if pid:
        os.kill(pid, signal.SIGTERM)
        return True
    return False


def run_standalone(config_path=None, toggle=False):
    """Show the border until killed. With toggle=True, stop it if already shown."""
    if toggle and stop_standalone():
        return 0
    stop_standalone()
    from PySide6 import QtCore, QtWidgets

    cfg = Config(config_path) if config_path else Config()
    settings = BorderSettings.from_config(cfg)
    app = QtWidgets.QApplication(sys.argv[:1])
    app.setQuitOnLastWindowClosed(False)
    screens = app.screens()
    screen = screens[settings.display] if settings.display < len(screens) else screens[0]
    border = create_border(settings, screen.geometry().height())
    border.show()
    with open(PID_FILE, "w") as f:
        f.write(str(os.getpid()))

    def quit_(*_):
        border.hide()
        app.quit()

    signal.signal(signal.SIGTERM, quit_)
    signal.signal(signal.SIGINT, quit_)
    timer = QtCore.QTimer()
    timer.timeout.connect(lambda: (quit_() if border.failed() else None))
    timer.start(250)
    try:
        return app.exec()
    finally:
        try:
            os.remove(PID_FILE)
        except OSError:
            pass
